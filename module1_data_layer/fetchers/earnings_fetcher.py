class EarningsRiskLevel(str, enum.Enum):
    """Risk level assigned to a stock based on days until earnings result.

    Rules:
      HIGH   → ≤ 2 days — binary event too close. Block all new setups.
      MEDIUM → 3-5 days — significant risk window. Warn + reduce confidence.
      LOW    → 6-10 days — on horizon. Note in setup card.
      NONE   → > 10 days — no near-term earnings risk.
    """

    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    NONE = "NONE"


class EarningsEvent(BaseModel):
    """A single earnings result event for a listed NSE stock.

    Carries full advisor-quality context: days to result, risk level,
    advisor warning, and estimated historical price reaction.

    Used by:
      M4 stock_screener — block/warn/note candidate setups
      M6 morning_brief — "Earnings this week" section
      Frontend setup card — inline earnings risk badge
    """

    ticker: str = Field(..., description="NSE ticker symbol e.g. INFY")
    company_name: str = Field(
        ..., description="Full company name e.g. Infosys Limited"
    )
    result_date: str = Field(
        ..., description="Result announcement date YYYY-MM-DD"
    )
    days_to_result: int = Field(
        ...,
        description="Calendar days from today to result_date. "
                    "0 = today, 1 = tomorrow, etc.",
    )
    result_type: str = Field(
        default="quarterly",
        description="quarterly / annual / half_yearly",
    )
    quarter: str = Field(
        default="",
        description="Quarter label e.g. Q4 FY26. Empty if annual.",
    )
    risk_level: EarningsRiskLevel = Field(
        ..., description="HIGH / MEDIUM / LOW / NONE based on days_to_result"
    )
    advisor_warning: str = Field(
        ...,
        description="Human-readable warning shown on setup card and morning brief.",
    )
    historical_reaction: str = Field(
        default="",
        description="Average ±% move on result day from historical data. "
                    "Empty when data unavailable.",
    )


class EarningsRisk(BaseModel):
    """Compact earnings risk summary attached to each setup card.

    Embedded inside TradeSetup (M4 models) so the frontend and M6
    always have the risk context alongside the trade levels.

    Exactly 4 fields — M4 screener and M6 morning brief depend on this shape.
    """

    has_upcoming_earnings: bool = Field(
        default=False,
        description="True if stock has earnings in the next 10 days.",
    )
    days_to_result: Optional[int] = Field(
        default=None,
        description="Days until result. None if no upcoming earnings.",
    )
    risk_level: EarningsRiskLevel = Field(
        default=EarningsRiskLevel.NONE,
        description="HIGH/MEDIUM/LOW/NONE",
    )
    advisor_warning: Optional[str] = Field(
        default=None,
        description="Short warning shown on setup card. None if no earnings risk.",
    )


