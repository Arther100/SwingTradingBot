"""
SwingAdvisorBot — Module 1: Data Layer
fetchers/earnings_fetcher.py — NSE corporate earnings calendar fetcher

Earnings events are binary risk events. A stock can move ±8-15% on
result day, making swing position sizing impossible. Every setup
generated by M4 must be checked against this calendar before being
shown to Vijay.

Risk classification by days until result:
  ≤ 2 days → HIGH   → Block setup entirely. No entry.
  3-5 days → MEDIUM → Warn. Reduce confidence score by 2.
  6-10 days → LOW   → Note. Show advisory in setup card.
  > 10 days → NONE  → No action needed.

Data source:
  NSE corporate announcements API:
  https://www.nseindia.com/api/corporate-announcements
    ?index=equities&from_date=DD-MM-YYYY&to_date=DD-MM-YYYY

  Filters for: "Quarterly Results", "Financial Results", "Annual Results".
  Date range: today → today + 10 trading days.
  Requires NseSessionManager cookies (same as FII/DII fetcher).

Caching:
  TTL: 3,600 seconds (1 hour).
  Cache key: "earnings:{YYYY-MM-DD}" — one entry per day.
  Returns cached dict[ticker → EarningsEvent] for fast per-stock lookup.

Models defined here (re-exported by models.py in File 04):
  EarningsRiskLevel — HIGH / MEDIUM / LOW / NONE
  EarningsEvent     — Full earnings event with advisor warning
  EarningsRisk      — Compact risk summary attached to each setup card

Usage:
  from module1_data_layer.fetchers.earnings_fetcher import earnings_fetcher

  # Fetch all upcoming earnings for a list of tickers
  events = await earnings_fetcher.fetch_upcoming(["INFY", "TCS", "HDFCBANK"])

  # Check single ticker
  risk = await earnings_fetcher.check_ticker("INFY")
  if risk and risk.risk_level == EarningsRiskLevel.HIGH:
      # Block setup
"""

from __future__ import annotations

import enum
import gzip
import json as _json
import logging
from datetime import datetime, timedelta
from typing import Optional

import httpx
from pydantic import BaseModel, Field
from zoneinfo import ZoneInfo

from module1_data_layer.cache import cache
from module1_data_layer.config import STOCK_METADATA
from module1_data_layer.fetchers.nse_session_manager import nse_session

IST = ZoneInfo("Asia/Kolkata")

logger = logging.getLogger("swing_advisor.fetchers.earnings")

# NSE corporate announcements endpoint
NSE_ANNOUNCEMENTS_URL = (
    "https://www.nseindia.com/api/corporate-announcements"
)

# Look ahead window for earnings risk detection
EARNINGS_LOOK_AHEAD_DAYS: int = 10

# Cache TTL: 1 hour (earnings calendar rarely changes intraday)
CACHE_TTL_EARNINGS: int = 3_600

# Request timeout
_TIMEOUT_SEC: float = 15.0

# Keywords that identify earnings/results announcements
_RESULTS_KEYWORDS: frozenset[str] = frozenset({
    "quarterly results",
    "financial results",
    "annual results",
    "q1 results",
    "q2 results",
    "q3 results",
    "q4 results",
    "half yearly results",
    "unaudited results",
    "audited results",
})

# NSE date format (DD-MM-YYYY)
_NSE_DATE_FMT = "%d-%m-%Y"
# ISO date format used internally
_ISO_DATE_FMT = "%Y-%m-%d"


