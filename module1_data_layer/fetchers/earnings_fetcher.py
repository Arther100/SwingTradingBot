def classify_earnings_risk(days_to_result: int) -> EarningsRiskLevel:
    """Classify earnings risk based on calendar days until result.

    Args:
        days_to_result: 0 = today, 1 = tomorrow, etc.

    Returns:
        EarningsRiskLevel enum value.

    Examples:
        >>> classify_earnings_risk(1)
        EarningsRiskLevel.HIGH
        >>> classify_earnings_risk(4)
        EarningsRiskLevel.MEDIUM
        >>> classify_earnings_risk(8)
        EarningsRiskLevel.LOW
        >>> classify_earnings_risk(15)
        EarningsRiskLevel.NONE
    """
    if days_to_result <= 2:
        return EarningsRiskLevel.HIGH
    elif days_to_result <= 5:
        return EarningsRiskLevel.MEDIUM
    elif days_to_result <= 10:
        return EarningsRiskLevel.LOW
    else:
        return EarningsRiskLevel.NONE


def _is_results_announcement(text: str) -> bool:
    """Return True if the announcement text indicates an earnings result event."""
    return any(keyword in text for keyword in _RESULTS_KEYWORDS)


def _parse_nse_date(date_str: str) -> Optional["date"]:
    """Parse an NSE date string into a Python date.

    NSE uses multiple formats:
      "22-May-2026"  → strptime("%d-%b-%Y")
      "2026-05-22"   → strptime("%Y-%m-%d")
      "22-05-2026"   → strptime("%d-%m-%Y")
    """
    date_str = str(date_str).strip()
    if not date_str:
        return None

    for fmt in ("%d-%b-%Y", "%Y-%m-%d", "%d-%m-%Y", "%d/%m/%Y"):
        try:
            return datetime.strptime(date_str, fmt).date()
        except ValueError:
            continue

    logger.debug(f"[Earnings] Could not parse date: '{date_str}'")
    return None


def _infer_result_type(text: str) -> tuple[str, str]:
    """Infer result type and quarter label from announcement text.

    Returns:
        (result_type, quarter_label)
        e.g. ("quarterly", "Q4 FY26") or ("annual", "FY26")
    """
    text = text.lower()

    # Detect fiscal year from text (e.g. "fy 2026", "fy26", "2025-26")
    import re
    fy_match = re.search(r"(?:fy\s?(\d{2,4})|(\d{4})-(\d{2}))", text)
    fy_label = ""
    if fy_match:
        if fy_match.group(1):
            yr = fy_match.group(1)
            fy_label = f"FY{yr[-2:]}" if len(yr) == 4 else f"FY{yr}"
        elif fy_match.group(2):
            fy_label = f"FY{fy_match.group(3)}"

    if "annual" in text or "year ended" in text or "full year" in text:
        return "annual", fy_label or "FY26"

    if "half" in text or "h1" in text or "h2" in text:
        half = "H1" if "h1" in text else "H2"
        return "half_yearly", f"{half} {fy_label}" if fy_label else half

    # Quarterly — detect Q1/Q2/Q3/Q4
    q_match = re.search(r"q([1-4])", text)
    if q_match:
        q_num = q_match.group(1)
        return "quarterly", f"Q{q_num} {fy_label}" if fy_label else f"Q{q_num}"

    # Infer quarter from month mentions
    month_to_quarter = {
        "june": "Q1", "jul": "Q1",
        "september": "Q2", "sep": "Q2",
        "december": "Q3", "dec": "Q3",
        "march": "Q4", "mar": "Q4",
    }
    for month, quarter in month_to_quarter.items():
        if month in text:
            return "quarterly", f"{quarter} {fy_label}" if fy_label else quarter

    return "quarterly", f"Q4 {fy_label}" if fy_label else "Q4 FY26"


def _build_advisor_warning(
    ticker: str,
    company_name: str,
    days_to_result: int,
    result_date_str: str,
    risk_level: EarningsRiskLevel,
) -> str:
    """Build a concise, actionable advisor warning for a setup card.

    Args:
        ticker: NSE ticker e.g. "INFY"
        company_name: Full name e.g. "Infosys Limited"
        days_to_result: Calendar days until result
        result_date_str: Human-readable date e.g. "Thu 22 May"
        risk_level: Classified risk level

    Returns:
        1-2 sentence warning string with concrete guidance.
    """
    day_word = "today" if days_to_result == 0 else (
        "tomorrow" if days_to_result == 1 else f"in {days_to_result} days"
    )

    if risk_level == EarningsRiskLevel.HIGH:
        return (
            f"{ticker} reports results {day_word} ({result_date_str}). "
            f"Do NOT enter any new swing position — results create binary "
            f"risk that invalidates all technical levels. "
            f"This setup is BLOCKED until post-result stability."
        )
    elif risk_level == EarningsRiskLevel.MEDIUM:
        return (
            f"{ticker} reports results {day_word} ({result_date_str}). "
            f"Significant earnings risk — a 5-10% gap is possible on result day. "
            f"If entering, use a hard stop and consider exiting before results."
        )
    else:  # LOW
        return (
            f"{ticker} results due {result_date_str} ({days_to_result} days). "
            f"Monitor the position — plan your exit before result week begins."
        )


