# Fetcher
# ─────────────────────────────────────────────────────────────


class EarningsFetcher:
    """Fetches NSE corporate earnings calendar for upcoming results.

    Pipeline:
      1. Check cache (TTL 1 hour) → return if fresh
      2. Build date range: today → today + 10 days (NSE DD-MM-YYYY format)
      3. GET NSE corporate-announcements API with session cookies
      4. Filter announcements for results-type events only
      5. Build dict[ticker → EarningsEvent] with risk classification
      6. Store in cache → return

    On failure: returns empty dict (pipeline is not blocked by missing
    earnings data — setup generator shows NO_EARNINGS_DATA note).
    """

    async def fetch_upcoming(
        self,
        tickers: Optional[list[str]] = None,
        days_ahead: int = EARNINGS_LOOK_AHEAD_DAYS,
    ) -> dict[str, EarningsEvent]:
        """Fetch earnings events for the next `days_ahead` calendar days.

        Args:
            tickers: If provided, only return events for these tickers.
                     If None, returns all NSE earnings events found.
            days_ahead: How many days ahead to scan (default 10).

        Returns:
            Dict mapping ticker → EarningsEvent.
            Empty dict if NSE is unreachable.
        """
        today = datetime.now(IST).date()
        cache_key = f"earnings:{today.strftime(_ISO_DATE_FMT)}"

        # ── Step 1: Cache hit ──────────────────────────────────
        cached = cache.get(cache_key)
        if cached is not None:
            logger.debug(f"[Earnings] Cache hit for {today}")
            if tickers:
                tickers_upper = {t.upper() for t in tickers}
                return {k: v for k, v in cached.items() if k in tickers_upper}
            return cached

        # ── Steps 2–5: Fetch and build calendar ───────────────
        end_date = today + timedelta(days=days_ahead)
        raw = await self._call_nse_api(today, end_date)

        if raw is None:
            logger.warning("[Earnings] NSE announcements API unreachable.")
            return {}

        calendar = self._parse_announcements(raw, today)

        # ── Step 6: Cache full calendar ────────────────────────
        cache.set(cache_key, calendar, CACHE_TTL_EARNINGS)

        logger.info(
            f"[Earnings] {len(calendar)} upcoming results found "
            f"({today} → {end_date})"
        )

        if tickers:
            tickers_upper = {t.upper() for t in tickers}
            return {k: v for k, v in calendar.items() if k in tickers_upper}
        return calendar

    async def check_ticker(
        self,
        ticker: str,
        days_ahead: int = EARNINGS_LOOK_AHEAD_DAYS,
    ) -> Optional[EarningsEvent]:
        """Check a single ticker for upcoming earnings risk.

        Convenience wrapper around fetch_upcoming() for M4's per-stock check.

        Args:
            ticker: NSE ticker symbol e.g. "INFY".
            days_ahead: Look-ahead window.

        Returns:
            EarningsEvent if the stock has results within days_ahead, else None.
        """
        calendar = await self.fetch_upcoming(
            tickers=[ticker], days_ahead=days_ahead
        )
        return calendar.get(ticker.upper())

    def build_earnings_risk(
        self, event: Optional[EarningsEvent]
    ) -> EarningsRisk:
        """Convert an EarningsEvent (or None) into a compact EarningsRisk.

        Used by M4 stock_screener to attach risk to each setup card.

        Args:
            event: EarningsEvent if the stock has upcoming earnings, else None.

        Returns:
            EarningsRisk with has_upcoming_earnings=False if event is None.
        """
        if event is None:
            return EarningsRisk()

        return EarningsRisk(
            has_upcoming_earnings=True,
            days_to_result=event.days_to_result,
            risk_level=event.risk_level,
            advisor_warning=event.advisor_warning,
        )

    # ─────────────────────────────────────────────────────────
    # Private helpers
    # ─────────────────────────────────────────────────────────

    async def _call_nse_api(
        self, from_date: "date", to_date: "date"
    ) -> Optional[list[dict]]:
        """GET NSE corporate announcements with session cookies.

        Args:
            from_date: Start date for the query window.
            to_date:   End date for the query window.

        Returns:
            Parsed JSON list on success, None on failure.
        """
        params = {
            "index": "equities",
            "from_date": from_date.strftime(_NSE_DATE_FMT),
            "to_date": to_date.strftime(_NSE_DATE_FMT),
        }

        for attempt in range(2):
            headers, cookies = await nse_session.get_session_context()
            try:
                async with httpx.AsyncClient(
                    follow_redirects=True,
                    timeout=_TIMEOUT_SEC,
                ) as client:
                    resp = await client.get(
                        NSE_ANNOUNCEMENTS_URL,
                        params=params,
                        headers=headers,
                        cookies=cookies,
                    )

                    if resp.status_code in (401, 403):
                        logger.warning(
                            f"[Earnings] NSE returned {resp.status_code} "
                            f"(attempt {attempt + 1}) — invalidating session."
                        )
                        nse_session.invalidate()
                        continue

                    resp.raise_for_status()

                    # NSE sends gzip-compressed JSON when Accept-Encoding is
                    # passed manually. Decompress if resp.json() fails.
                    try:
                        data = resp.json()
                    except (ValueError, UnicodeDecodeError):
                        try:
                            raw = gzip.decompress(resp.content)
                            data = _json.loads(raw)
                        except Exception as decomp_err:
                            logger.warning(
                                f"[Earnings] Failed to decode NSE response: {decomp_err}"
                            )
                            return None

                    if isinstance(data, list):
                        return data
                    # Some NSE endpoints wrap in {"data": [...]}
                    if isinstance(data, dict) and "data" in data:
                        return data["data"]

                    logger.warning(
                        f"[Earnings] Unexpected response type: "
                        f"{type(data).__name__}"
                    )
                    return None

            except httpx.TimeoutException:
                logger.warning(
                    f"[Earnings] NSE API timed out (attempt {attempt + 1})."
                )
            except httpx.HTTPStatusError as exc:
                logger.warning(
                    f"[Earnings] NSE HTTP error {exc.response.status_code}"
                )
                return None
            except Exception as exc:
                logger.warning(f"[Earnings] Unexpected error: {exc}")
                return None

        return None

    def _parse_announcements(
        self,
        data: list[dict],
        today: "date",
    ) -> dict[str, EarningsEvent]:
        """Parse NSE corporate announcements into a ticker → EarningsEvent map.

        Filters to results-type announcements only.
        Deduplicates: keeps the nearest result date per ticker.

        NSE announcement object shape (typical):
          {
            "symbol":   "INFY",
            "series":   "EQ",
            "subject":  "Financial Results for the quarter ended March 2026",
            "bm_desc":  "Board Meeting",
            "date":     "22-May-2026",       # board meeting date
            "recDate":  "",
            "purpose":  "Quarterly Results"  # can also be in subject
          }

        Note: NSE sometimes uses "date" in "22-May-2026" format,
        other times "bm_date" in "2026-05-22" format.
        Both are handled below.

        Returns:
            dict[ticker → EarningsEvent] with nearest result per ticker.
        """
        calendar: dict[str, EarningsEvent] = {}

        for item in data:
            # ── Extract ticker ─────────────────────────────────
            ticker = (
                str(item.get("symbol") or item.get("scrip_cd") or "")
                .upper()
                .strip()
            )
            if not ticker:
                continue

            # ── Check if this is a results announcement ────────
            subject = str(item.get("subject") or item.get("desc") or "").lower()
            purpose = str(item.get("purpose") or item.get("bm_desc") or "").lower()
            combined_text = f"{subject} {purpose}"

            if not _is_results_announcement(combined_text):
                continue

            # ── Parse announcement date ────────────────────────
            result_date = _parse_nse_date(
                item.get("date") or item.get("bm_date") or ""
            )
            if result_date is None:
                continue

            # Must be on or after today
            if result_date < today:
                continue

            days_to_result = (result_date - today).days

            # ── Deduplicate: keep nearest result date ──────────
            if ticker in calendar:
                existing = calendar[ticker]
                if days_to_result >= existing.days_to_result:
                    continue  # Keep the closer one

            # ── Classify risk ──────────────────────────────────
            risk_level = classify_earnings_risk(days_to_result)

            # ── Determine result type + quarter ───────────────
            result_type, quarter = _infer_result_type(combined_text)

            # ── Company name from STOCK_METADATA ──────────────
            company_name = STOCK_METADATA.get(ticker, {}).get(
                "company_name", ticker
            )

            # ── Advisor warning ────────────────────────────────
            advisor_warning = _build_advisor_warning(
                ticker=ticker,
                company_name=company_name,
                days_to_result=days_to_result,
                result_date_str=result_date.strftime("%a %d %b"),
                risk_level=risk_level,
            )

            calendar[ticker] = EarningsEvent(
                ticker=ticker,
                company_name=company_name,
                result_date=result_date.strftime(_ISO_DATE_FMT),
                days_to_result=days_to_result,
                result_type=result_type,
                quarter=quarter,
                risk_level=risk_level,
                advisor_warning=advisor_warning,
            )

        return calendar


